const makeNav = (points, start, drift, noise) => {
  const arr = [];
  let v = start;
  for (let i = 0; i < points; i++) {
    const n = (Math.sin(i * 1.7) + Math.cos(i * 0.9)) * 0.5 * noise;
    v = Math.max(0.6, v * (1 + drift + n));
    arr.push(Number(v.toFixed(4)));
  }
  return arr;
};

